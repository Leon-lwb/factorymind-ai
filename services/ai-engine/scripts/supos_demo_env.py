"""Prepare the FactoryMind AI engine to run against the live open supOS instance.

The gateway reads the `supos_community_token` cookie, not an `Authorization`
header, so `SUPOS_API_TOKEN` must carry a Keycloak **access token**. On this
open supOS CE `V1.5.0.0-M` box the `supos` realm issues 12-hour access tokens,
which comfortably outlives a demo recording — no Keycloak admin changes needed.

It writes `factorymind-ai/.env` (never committed) and prints what it set.

Usage
-----
    py -3 supos_demo_env.py
    py -3 supos_demo_env.py --gateway http://192.168.1.65:18088 --mqtt-host 192.168.1.65
"""

from __future__ import annotations

import argparse
import base64
import json
import os
from pathlib import Path

import httpx

REALM = "supos"
CLIENT_ID = "supos"
# open supOS CE ships this client secret in its own deploy config; it is not a
# FactoryMind secret. Override with SUPOS_CLIENT_SECRET for any other instance.
CLIENT_SECRET = os.environ.get("SUPOS_CLIENT_SECRET", "VaOS2makbDhJJsLlYPt4Wl87bo9VzXiO")
CE_USER = os.environ.get("SUPOS_USERNAME", "supos")
CE_PASSWORD = os.environ.get("SUPOS_PASSWORD", "supos")
ENV_PATH = Path(__file__).resolve().parents[3] / ".env"


def user_token(keycloak: str) -> str:
    r = httpx.post(
        f"{keycloak}/realms/{REALM}/protocol/openid-connect/token",
        data={"grant_type": "password", "client_id": CLIENT_ID,
              "client_secret": CLIENT_SECRET, "username": CE_USER, "password": CE_PASSWORD},
        timeout=20,
    )
    r.raise_for_status()
    return r.json()["access_token"]


def token_ttl_minutes(token: str) -> float:
    payload = token.split(".")[1]
    payload += "=" * (-len(payload) % 4)
    claims = json.loads(base64.urlsafe_b64decode(payload))
    return (claims["exp"] - claims["iat"]) / 60


def write_env(gateway: str, mqtt_host: str, token: str) -> None:
    lines = [
        "# Generated by scripts/supos_demo_env.py — real open supOS wiring.",
        "# Do not commit: holds a live Keycloak access token.",
        "",
        "AI_PROVIDER=mock",
        "",
        "DATA_PROVIDER=supos",
        f"SUPOS_API_URL={gateway}",
        f"SUPOS_API_TOKEN={token}",
        "SUPOS_TIMEOUT_SECONDS=20",
        "SUPOS_VERIFY_TLS=false",
        "SUPOS_UNS_ROOT_ALIAS=",
        "SUPOS_EVENT_SOURCE=mqtt",
        f"SUPOS_MQTT_URL=mqtt://{mqtt_host}:1883",
        "SUPOS_MQTT_TOPIC=factorymind/uns/#",
        "",
    ]
    ENV_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"env: wrote {ENV_PATH}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--gateway", default="http://192.168.1.65:18088")
    parser.add_argument("--keycloak", default="http://192.168.1.65:18081")
    parser.add_argument("--mqtt-host", default="192.168.1.65")
    args = parser.parse_args()

    token = user_token(args.keycloak)
    print(f"keycloak: token minted, ttl={token_ttl_minutes(token):.0f} min")
    write_env(args.gateway, args.mqtt_host, token)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
